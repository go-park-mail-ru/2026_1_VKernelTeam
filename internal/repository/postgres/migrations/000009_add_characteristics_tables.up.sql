-- Определения доступных характеристик для категорий
CREATE TABLE category_characteristic (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    category_id bigint NOT NULL REFERENCES category(id) ON DELETE CASCADE,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
    allowed_values text[] DEFAULT NULL,
    sort_order int NOT NULL DEFAULT 0
);

-- Значения категорийных характеристик конкретного объявления
CREATE TABLE product_characteristic (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    category_characteristic_id bigint NOT NULL REFERENCES category_characteristic(id) ON DELETE CASCADE,
    value text NOT NULL CHECK (length(value) BETWEEN 1 AND 500),
    UNIQUE (product_id, category_characteristic_id)
);

-- Пользовательские характеристики объявления
CREATE TABLE product_custom_characteristic (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
    value text NOT NULL CHECK (length(value) BETWEEN 1 AND 500),
    UNIQUE (product_id, name)
);

